import { createServer } from 'vite';
import { chromium } from 'playwright';
import path from 'node:path';
const ROOT = path.resolve(process.env.GAME_ROOT || process.cwd());
const server = await createServer({ root: ROOT, logLevel: 'error', server: { port: 0, host: '127.0.0.1' } });
await server.listen();
const url = server.resolvedUrls.local[0].replace(/\/$/, '');
const browser = await chromium.launch({ headless: true, args: ['--use-gl=angle', '--use-angle=metal', '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
await page.goto(url, { waitUntil: 'load', timeout: 120000 });
await page.waitForTimeout(2500);
await page.screenshot({ path: '/tmp/menu_shot.png' });
await page.keyboard.press('Space');
await page.waitForFunction(() => window.__GAME && window.__GAME.ready === true, null, { timeout: 180000, polling: 250 });
await page.waitForTimeout(2500);
await page.screenshot({ path: '/tmp/game_shot.png' });
const dismissed = await page.evaluate(() => window.__MENU_DISMISSED === true);
console.log('menu dismissed:', dismissed);
await browser.close();
await server.close();
